// ABOUTME: Resolves keyboard navigation for a horizontal set of product tabs.
// ABOUTME: Wraps arrow navigation and supports direct first and last selection.
export function getTabIndex(key: string, current: number, count: number): number | null {
  switch (key) {
    case "ArrowRight":
      return (current + 1) % count;
    case "ArrowLeft":
      return (current - 1 + count) % count;
    case "Home":
      return 0;
    case "End":
      return count - 1;
    default:
      return null;
  }
}
